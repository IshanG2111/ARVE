"""Markdown generator for ARVE security assessment reports."""
from __future__ import annotations

from app.reports.schemas import ScanReportData


def generate_markdown_report(report: ScanReportData) -> str:
    """Generate a clean, structured GitHub-Flavored Markdown security report."""
    md: list[str] = []

    # Title & Header
    md.append("# ARVE Security Report")
    md.append("### Automated Repository Security & Code Intelligence Assessment\n")
    
    if report.is_ai_fallback:
        md.append(f"> **Mode**: **Deterministic Fallback** — {report.ai_status_message or 'Generated via canonical rules engine.'}\n")
    else:
        md.append(f"> **Mode**: **Active AI** — Generated by {report.ai_model} over canonical scanner evidence.\n")

    # Metadata Table
    repo_display = report.repository_name or report.project_name
    commit_short = report.commit_sha[:8] if report.commit_sha else "N/A"
    ai_status_tag = "Deterministic Fallback" if report.is_ai_fallback else f"Active AI ({report.ai_model})"

    md.append("| Metadata | Details |")
    md.append("| :--- | :--- |")
    md.append(f"| **Target Repository** | `{repo_display}` |")
    md.append(f"| **Project Name** | {report.project_name} |")
    md.append(f"| **Scan ID** | `{report.scan_id[:16]}` |")
    md.append(f"| **Commit SHA** | `{commit_short}` |")
    md.append(f"| **Scan Timestamp** | {report.scan_timestamp} |")
    md.append(f"| **Scan Status** | **{report.scan_status}** |")
    md.append(f"| **AI Analysis Mode** | {ai_status_tag} |")
    md.append("\n---\n")

    # 01 — Executive Summary
    crit = report.severity_counts.get("CRITICAL", 0)
    high = report.severity_counts.get("HIGH", 0)
    med = report.severity_counts.get("MEDIUM", 0)
    low = report.severity_counts.get("LOW", 0)

    md.append("## 01 — Executive Summary\n")
    md.append(f"{report.executive_summary}\n")
    md.append("\n---\n")

    # 02 — Security Overview
    md.append("## 02 — Security Overview\n")
    md.append("### Severity Breakdown\n")
    md.append("| Severity | Count | Risk Classification | Action SLA |")
    md.append("| :--- | :---: | :--- | :--- |")
    md.append(f"| 🔴 **Critical** | **{crit}** | Immediate compromise potential | Within 24h SLA |")
    md.append(f"| 🟠 **High** | **{high}** | Severe vulnerability requiring urgent fix | Within 7 days |")
    md.append(f"| 🟡 **Medium** | **{med}** | Defense-in-depth or standard flaw | Scheduled Sprint |")
    md.append(f"| 🔵 **Low / Info** | **{low}** | Hygiene issue or best-practice divergence | Maintenance Backlog |")
    md.append(f"| **Total Findings** | **{report.total_findings}** | All detected issues across enabled engines | Continuous Triage |\n")

    if report.priority_risks:
        md.append("### Priority Risks (What needs attention?)\n")
        for pr in report.priority_risks:
            md.append(f"#### {pr.index}. {pr.title}")
            md.append(f"- **Severity**: `{pr.severity}`")
            md.append(f"- **Details**: {pr.description}")
            md.append(f"- **Target**: {pr.target}")
            if pr.related_finding_ids:
                md.append(f"- **Related Findings**: {', '.join(pr.related_finding_ids)}")
            if pr.severity_footnote:
                md.append(f"- _{pr.severity_footnote}_")
            md.append("")

    md.append("\n---\n")

    # 03 — Important Findings
    md.append("## 03 — Important Findings\n")
    md.append("Detailed vulnerability cards for high-priority findings:\n\n")

    if not report.important_findings:
        md.append("_No critical or high-severity vulnerabilities were identified during this scan._\n")
    else:
        for finding in report.important_findings:
            loc = finding.file_path or "package-lock.json"
            if finding.line_start:
                loc += f":{finding.line_start}"

            ids = []
            if finding.ghsa:
                ids.append(finding.ghsa)
            if finding.cve:
                ids.append(finding.cve)
            if finding.cwe:
                ids.append(finding.cwe)
            ids.append(finding.engine.upper())
            id_bar = " · ".join(ids)

            md.append(f"### {finding.display_id} — {finding.title}\n")
            md.append(f"**Severity**: `{finding.severity}`  \n**Identifiers**: `{id_bar}`\n")
            md.append(f"**What is wrong?**  \n{finding.issue_summary or finding.description or 'No summary provided.'}\n")
            
            # Affected component table
            md.append("| Property | Value |")
            md.append("| :--- | :--- |")
            if finding.package_name:
                md.append(f"| **Package** | `{finding.package_name}` |")
            if finding.package_version:
                md.append(f"| **Installed** | `{finding.package_version}` |")
            if finding.fixed_version:
                md.append(f"| **Fixed version** | `{finding.fixed_version}` |")
            md.append(f"| **Location** | `{loc}` |")
            md.append(f"| **Detection** | {finding.engine.upper()} |")
            md.append("")

            md.append(f"**Potential impact**  \n{finding.potential_impact or 'Degrades application defense posture.'}\n")
            md.append(f"**Applicability**  \n{finding.applicability}\n")
            md.append(f"**Recommended fix**  \n{finding.recommended_fix or 'Update to secure version.'}\n")
            if finding.ghsa or finding.cve:
                ref = finding.ghsa or finding.cve
                md.append(f"**Advisory reference**: `{ref}` · Status: **{finding.status}**\n")
            md.append("")

    md.append("\n---\n")

    # 04 — AI Recommendations
    md.append("## 04 — AI Recommendations\n")
    md.append("Consolidated remediation plan triaged by exposure and applicability:\n\n")

    p1_items = [a for a in report.prioritized_actions if "1" in a.priority]
    p2_items = [a for a in report.prioritized_actions if "2" in a.priority]
    p3_items = [a for a in report.prioritized_actions if "3" in a.priority]

    if p1_items:
        md.append("### Immediate Attention (Priority 1)\n")
        for a in p1_items:
            md.append(f"- **{a.action}** ({a.rationale})")
        md.append("")

    if p2_items:
        md.append("### Next (Priority 2)\n")
        for a in p2_items:
            md.append(f"- **{a.action}** ({a.rationale})")
        md.append("")

    if p3_items:
        md.append("### Maintenance (Priority 3)\n")
        for a in p3_items:
            md.append(f"- **{a.action}** ({a.rationale})")
        md.append("")

    if not (p1_items or p2_items or p3_items):
        for idx, rec in enumerate(report.ai_recommendations, 1):
            md.append(f"{idx}. {rec}")
        md.append("")

    if report.consolidated_remediations:
        md.append("### Consolidated Package Upgrades\n")
        for fix in report.consolidated_remediations:
            md.append(f"- {fix}")
        md.append("")

    md.append("\n---\n")

    # 05 — Analysis Coverage
    md.append("## 05 — Analysis Coverage\n")
    md.append("### Scanner Engines & Code Intelligence\n")
    md.append("| Engine / Analysis | Status | Scope & Purpose | Duration / Metrics | Findings |\n")
    md.append("| :--- | :---: | :--- | :---: | :---: |\n")
    for eng in report.engine_coverage:
        dur = f"{eng.duration_ms}ms" if eng.duration_ms else "Completed" if eng.status == "Completed" else "Not run"
        md.append(f"| **{eng.engine_name}** | `{eng.status}` | {eng.purpose} | {dur} | {eng.findings_count} |")
    md.append("")

    if report.ast_coverage and report.ast_coverage.data_available:
        ast = report.ast_coverage
        md.append("### AST Code Intelligence Summary\n")
        md.append(f"- **Status**: `{ast.status}`")
        md.append(f"- **Discovered Entities**: {ast.total_functions} functions, {ast.total_classes} classes, {ast.total_imports} imports")
        md.append(f"- **Cross-Component Relationships**: {ast.total_relationships} caller/callee links mapped across {ast.files_parsed} files")
        md.append("")
    else:
        md.append("### AST Code Intelligence Summary\n")
        md.append("- **Status**: `Not indexed` (Structural indexing was not executed for this snapshot)\n")

    if report.provenance:
        p = report.provenance
        md.append("### AI Generation Provenance\n")
        md.append("| Metadata Field | Value |")
        md.append("| :--- | :--- |")
        md.append(f"| **Provider** | `{p.provider}` |")
        md.append(f"| **Model** | `{p.model}` |")
        md.append(f"| **Prompt Version** | `{p.prompt_version}` |")
        md.append(f"| **Generation Status** | `{p.generation_status}` |")
        md.append(f"| **Cache Status** | `{p.cache_status}` |")
        md.append(f"| **Input Hash** | `{p.input_hash[:16]}...` |")
        if p.input_tokens is not None:
            md.append(f"| **Tokens (In / Out)** | {p.input_tokens} / {p.output_tokens or 0} |")
        if p.latency_ms is not None:
            md.append(f"| **Latency** | {p.latency_ms}ms |")
        md.append("")

    if report.limitations:
        md.append("### Analysis Limitations\n")
        for lim in report.limitations:
            md.append(f"- {lim}")
        md.append("")

    md.append("\n---\n")

    # 06 — Technical Appendix
    md.append("## 06 — Technical Appendix\n")
    md.append(f"Comprehensive inventory of all {len(report.appendix_findings)} canonical findings discovered in this scan:\n\n")

    if not report.appendix_findings:
        md.append("_No findings recorded._\n")
    else:
        md.append("| ID | Severity | Vulnerability | Location | Detection Engine | Status |")
        md.append("| :---: | :--- | :--- | :--- | :---: | :---: |")
        for f in report.appendix_findings:
            loc = f"{f.file_path or f.package_name or 'N/A'}"
            if f.line_start:
                loc += f":{f.line_start}"
            clean_title = f.title.replace("|", "/")
            md.append(f"| **{f.display_id}** | `{f.severity}` | {clean_title} | `{loc}` | {f.engine.upper()} | {f.status} |")
        md.append("")

    return "\n".join(md)
