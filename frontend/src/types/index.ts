// ─── Security Findings (Phase 4 / Normalized Engine Contract) ───────────────
export type FindingSeverity = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW' | 'INFO';

export type FindingConfidence = 'HIGH' | 'MEDIUM' | 'LOW';

export type FindingType =
  | 'dependency'
  | 'secret'
  | 'sast'
  | 'iac'
  | 'container'
  | 'configuration';

export type FindingStatus =
  | 'OPEN'
  | 'ACKNOWLEDGED'
  | 'RESOLVED'
  | 'REOPENED'
  | 'FALSE_POSITIVE'
  | 'SUPPRESSED';

export interface SecurityFinding {
  id: string;
  scan_id?: string;
  project_id?: string;
  engine: string;
  finding_type: FindingType | string;
  title: string;
  description?: string;
  severity: FindingSeverity | string;
  confidence?: FindingConfidence | string;
  status: FindingStatus | string;
  file_path?: string;
  line_start?: number;
  line_end?: number;
  package_name?: string;
  package_version?: string;
  fixed_version?: string;
  ecosystem?: string;
  cve?: string;
  ghsa?: string;
  cwe?: string;
  rule_id?: string;
  suppression_reason?: string;
  suppression_justification?: string;
  suppression_expires_at?: string;
  fingerprint?: string;
  raw_json?: any;
  created_at?: string;
  updated_at?: string;
}

// ─── AI explanations ────────────────────────────────────────────────────────
export interface AIStatus {
  enabled: boolean;
  model?: string | null;
  private_repos_allowed: boolean;
}

// VALIDATED: AI answer that passed the backend checks. FALLBACK: standard guidance, with `reason`.
export type AIResultStatus = 'VALIDATED' | 'FALLBACK';

export interface FindingExplanation {
  summary: string;
  why_it_matters: string;
  fix_steps: string[];
  suggested_code?: string | null;
  references_used: string[];
  caveats: string[];
}

export interface FindingExplanationResponse {
  status: AIResultStatus;
  reason?: string | null;
  cached: boolean;
  model?: string | null;
  prompt_version?: string | null;
  scan_id: string;
  finding_id: string;
  commit_sha: string;
  code_source?: 'ast' | 'lines' | null;
  code_symbol?: string | null;
  explanation: FindingExplanation;
}

export interface ScanSummary {
  overview: string;
  top_risks: string[];
  first_actions: string[];
}

export interface ScanSummaryRef {
  finding_id: string;
  title: string;
  severity: string;
}

export interface ScanSummaryResponse {
  status: AIResultStatus;
  reason?: string | null;
  cached: boolean;
  model?: string | null;
  prompt_version?: string | null;
  scan_id: string;
  commit_sha: string;
  refs: Record<string, ScanSummaryRef>;
  summary: ScanSummary;
}
